# ── Función de limpieza y normalización de texto ──────────────────────────────
def limpiar_texto(texto: str) -> str:
    """Normaliza el texto para el clasificador: minúsculas, solo letras y espacios."""
    texto = texto.lower()
    texto = re.sub(r'[^a-záéíóúüñ\s]', ' ', texto)  # Solo letras españolas y espacios
    texto = re.sub(r'\s+', ' ', texto).strip()        # Eliminar espacios múltiples
    return texto

