# ── Función para formatear documentos recuperados por FAISS ──────────────────
def formatear_contexto(docs: list) -> str:
    """
    Convierte la lista de fragmentos recuperados por FAISS en un bloque de texto
    estructurado con metadata visible (fuente y página) para el LLM.
    """
    bloques = []
    for i, doc in enumerate(docs, 1):
        fuente = doc.metadata.get('source', 'Documento desconocido')
        pagina = doc.metadata.get('page', 'N/A')
        # Limpiar el nombre del archivo para presentación
        nombre_limpio = fuente.replace('_', ' ').replace('.pdf', '')
        bloque = (
            f"[Fragmento {i} | Documento: {nombre_limpio} | Página: {pagina}]\n"
            f"{doc.page_content.strip()}"
        )
        bloques.append(bloque)
    return '\n\n---\n\n'.join(bloques)


def extraer_fuente_principal(docs: list) -> tuple:
    """
    Retorna (documento_principal, páginas_citadas) basado en los fragmentos recuperados.
    El documento principal es el que aparece más veces en los resultados.
    """
    from collections import Counter
    if not docs:
        return ('Sin fuente', 'N/A')
    fuentes = [doc.metadata.get('source', 'desconocido') for doc in docs]
    paginas = sorted(set(
        str(doc.metadata.get('page', 'N/A'))
        for doc in docs
        if doc.metadata.get('source') == Counter(fuentes).most_common(1)[0][0]
    ))
    doc_principal = Counter(fuentes).most_common(1)[0][0]
    paginas_str   = ', '.join(paginas)
    return (doc_principal, paginas_str)


# ── Función principal: pipeline PQRS completo ─────────────────────────────────
def procesar_pqrs(pregunta: str, usuario: str = 'usuario', chat_id: str = '0') -> dict:
    """
    Ejecuta el pipeline completo de PQRS para Mercado Libre:
    A. Clasificar consulta (Random Forest + TF-IDF)
    B. Recuperar fragmentos relevantes (FAISS RAG)
    C. Generar respuesta (GPT-4o con contexto documental)
    D. Registrar en SQLite
    E. Retornar resultado estructurado

    Returns:
        dict con: id_registro, tipo_pqrs, confianza, respuesta,
                  fuente_doc, pagina_fuente, n_fragmentos
    """
    # ── A: Clasificación PQRS con Random Forest ────────────────────────────────
    clasificacion = clasificar_pqrs(pregunta)
    tipo_pqrs     = clasificacion['categoria']
    confianza     = clasificacion['confianza']

    # ── B: Recuperación RAG desde FAISS ───────────────────────────────────────
    # El retriever devuelve los k fragmentos más similares semánticamente
    docs_relevantes = retriever.invoke(pregunta)
    contexto        = formatear_contexto(docs_relevantes)
    fuente_doc, pagina_fuente = extraer_fuente_principal(docs_relevantes)

    # ── C: Generación de respuesta con LangChain + LLM ────────────────────────
    # La cadena: prompt → LLM → parser de texto plano
    chain     = prompt_pqrs_ml | llm | StrOutputParser()
    respuesta = chain.invoke({
        'pregunta'  : pregunta,
        'tipo_pqrs' : tipo_pqrs,
        'confianza' : f'{confianza:.1%}',
        'contexto'  : contexto
    })

    # ── D: Registro en SQLite para auditoría ──────────────────────────────────
    id_registro = registrar_pqrs(
        conn=db_conn,
        usuario=usuario,
        chat_id=chat_id,
        pregunta=pregunta,
        respuesta=respuesta,
        tipo_pqrs=tipo_pqrs,
        documento_fuente=fuente_doc,
        pagina_fuente=pagina_fuente,
        score_similitud=confianza
    )

    # ── E: Retornar resultado estructurado ─────────────────────────────────────
    return {
        'id_registro'   : id_registro,
        'tipo_pqrs'     : tipo_pqrs,
        'confianza'     : confianza,
        'respuesta'     : respuesta,
        'fuente_doc'    : fuente_doc,
        'pagina_fuente' : pagina_fuente,
        'n_fragmentos'  : len(docs_relevantes)
    }


