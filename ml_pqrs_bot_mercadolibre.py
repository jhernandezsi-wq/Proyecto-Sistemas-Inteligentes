# Script DDL — define la estructura de la tabla de registros
SQL_CREATE_TABLE = """
CREATE TABLE IF NOT EXISTS pqrs_logs (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    fecha            TEXT    NOT NULL,
    usuario          TEXT    NOT NULL,
    chat_id          TEXT    NOT NULL,
    pregunta         TEXT    NOT NULL,
    respuesta        TEXT    NOT NULL,
    tipo_pqrs        TEXT    NOT NULL,
    documento_fuente TEXT,
    pagina_fuente    TEXT,
    score_similitud  REAL
);
"""

def init_db() -> sqlite3.Connection:
    """Inicializa la base de datos SQLite y retorna la conexión activa."""
    conn = sqlite3.connect(CONFIG['db_path'], check_same_thread=False)
    conn.execute(SQL_CREATE_TABLE)
    conn.commit()
    return conn

def registrar_pqrs(
    conn: sqlite3.Connection,
    usuario: str,
    chat_id: str,
    pregunta: str,
    respuesta: str,
    tipo_pqrs: str,
    documento_fuente: str = None,
    pagina_fuente: str = None,
    score_similitud: float = None
) -> int:
    """Registra una consulta PQRS en la base de datos y retorna el id."""
    fecha = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    cursor = conn.execute(
        """
        INSERT INTO pqrs_logs
            (fecha, usuario, chat_id, pregunta, respuesta,
             tipo_pqrs, documento_fuente, pagina_fuente, score_similitud)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        """,
        (fecha, usuario, chat_id, pregunta, respuesta,
         tipo_pqrs, documento_fuente, pagina_fuente, score_similitud)
    )
    conn.commit()
    return cursor.lastrowid

def obtener_estadisticas(conn: sqlite3.Connection) -> dict:
    """Devuelve estadísticas de uso del sistema PQRS para el comando /estadisticas."""
    total    = conn.execute('SELECT COUNT(*) FROM pqrs_logs').fetchone()[0]
    por_tipo = conn.execute(
        'SELECT tipo_pqrs, COUNT(*) as cnt FROM pqrs_logs GROUP BY tipo_pqrs ORDER BY cnt DESC'
    ).fetchall()
    por_doc  = conn.execute(
        'SELECT documento_fuente, COUNT(*) as cnt FROM pqrs_logs '
        'WHERE documento_fuente IS NOT NULL GROUP BY documento_fuente ORDER BY cnt DESC LIMIT 5'
    ).fetchall()
    return {
        'total'   : total,
        'por_tipo': dict(por_tipo),
        'por_doc' : dict(por_doc)
    }

