def cargar_pdfs_mercadolibre(directorio: str) -> list:
    """
    Carga automáticamente todos los PDFs de un directorio usando PyPDFLoader.
    Enriquece cada documento con metadata: nombre del PDF y número de página.
    Si no hay PDFs, informa al usuario cómo proceder.
    """
    documentos = []
    archivos_pdf = sorted([f for f in os.listdir(directorio) if f.endswith('.pdf')])

    if not archivos_pdf:
        print('⚠️  No se encontraron PDFs en', directorio)
        print('   Por favor sube los PDFs en el Paso 6a y vuelve a ejecutar esta celda.')
        return []

    for nombre_pdf in archivos_pdf:
        ruta = os.path.join(directorio, nombre_pdf)
        try:
            # PyPDFLoader carga cada página como un documento independiente
            loader = PyPDFLoader(ruta)
            paginas = loader.load()
            # Enriquecer metadata con nombre legible del archivo
            for pag in paginas:
                pag.metadata['source'] = nombre_pdf
                pag.metadata['doc_type'] = 'mercadolibre_oficial'
            documentos.extend(paginas)
            print(f'  ✅ {nombre_pdf}: {len(paginas)} página(s) cargadas')
        except Exception as e:
            print(f'  ❌ Error cargando {nombre_pdf}: {e}')

    return documentos


