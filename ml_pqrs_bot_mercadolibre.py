    # Intentar cargar índice FAISS existente desde disco
    if os.path.exists(CONFIG['faiss_index_path']) and not forzar_reconstruccion:
        print('📂 Cargando índice FAISS existente desde disco...')
        vs = FAISS.load_local(
            CONFIG['faiss_index_path'],
            embeddings,
            allow_dangerous_deserialization=True  # Necesario para FAISS local
        )
        print(f'✅ Índice FAISS cargado correctamente.')
        return vs

    if not documentos:
        raise ValueError('No hay documentos para indexar. Sube los PDFs primero.')

    # Fragmentar documentos con RecursiveCharacterTextSplitter
    # Los separadores respetan la estructura natural del texto (párrafos > líneas > oraciones)
    splitter = RecursiveCharacterTextSplitter(
        chunk_size=CONFIG['chunk_size'],
        chunk_overlap=CONFIG['chunk_overlap'],
        separators=['\n\n', '\n', '. ', ', ', ' ', '']  # Jerarquía de separadores
    )
    fragmentos = splitter.split_documents(documentos)

    print(f'\n📋 Fragmentación completada:')
    print(f'   • Documentos originales (páginas) : {len(documentos)}')
    print(f'   • Fragmentos generados             : {len(fragmentos)}')
    print(f'   • Tamaño por fragmento             : {CONFIG["chunk_size"]} chars')
    print(f'   • Solapamiento                     : {CONFIG["chunk_overlap"]} chars')

    # Generar embeddings y construir el índice FAISS
    print('\n🔄 Generando embeddings (OpenAI text-embedding-3-small)...')
    print('   Esto puede tardar 1-2 minutos dependiendo del tamaño de los PDFs...')
    vector_store = FAISS.from_documents(fragmentos, embeddings)

    # Persistir el índice en disco para reutilización en sesiones futuras
    vector_store.save_local(CONFIG['faiss_index_path'])
    print(f'\n✅ Índice FAISS construido y guardado en: {CONFIG["faiss_index_path"]}')

    return vector_store


